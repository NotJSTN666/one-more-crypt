export type PixelIcon = keyof typeof ART;

/** The icon as markup: a 16x16 pixel image that scales with the text around it. */
export function pxi(name: PixelIcon, cls = ''): string {
  return `<i class="pxi pxi-${name}${cls ? ` ${cls}` : ''}" aria-hidden="true"></i>`;
}

/** Bake every icon and add the stylesheet that draws them (once, at start). */
export function installPixelIcons() {
  if (typeof document === 'undefined' || document.getElementById('pxi-style')) return;
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = 16;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;
  const rules: string[] = [];
  for (const [name, rows] of Object.entries(ART)) {
    ctx.clearRect(0, 0, 16, 16);
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        const c = PAL[row[x]];
        if (!c) continue;
        ctx.fillStyle = c;
        ctx.fillRect(x, y, 1, 1);
      }
    });
    rules.push(`.pxi-${name}{background-image:url(${canvas.toDataURL()})}`);
  }
  const style = document.createElement('style');
  style.id = 'pxi-style';
  style.textContent = rules.join('\n');
  document.head.appendChild(style);
}

