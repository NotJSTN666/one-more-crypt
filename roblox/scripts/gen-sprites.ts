// Writes roblox/src/shared/Sprites.luau from the web game's pixel art, so the Roblox
// voxel models always match the 12x12 sprites in src/sprites.ts and src/enemy-art.ts.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ENEMY_ART } from '../../src/enemy-art';
import { CLOAKS } from '../../src/hero';
import { ART, PALETTE } from '../../src/sprites';

const q = (s: string) => JSON.stringify(s);
const rows = (r: string[]) => `{ ${r.map(q).join(', ')} }`;
const hex = (h: string) => `Color3.fromHex(${q(h)})`;

const out: string[] = [
  '--!strict',
  '-- Generated by roblox/scripts/gen-sprites.ts from the web game\'s pixel art. Do not edit.',
  '',
  'local Sprites = {}',
  '',
  'Sprites.PALETTE = {',
  ...Object.entries(PALETTE).map(([k, v]) => `\t[${q(k)}] = ${hex(v)},`),
  '}',
  '',
  '-- Cloak colours (p light, P dark) by hero.',
  'Sprites.CLOAKS = {',
  ...Object.entries(CLOAKS).map(([k, v]) => `\t${k} = { p = ${hex(v.p)}, P = ${hex(v.P)} },`),
  '}',
  '',
  'Sprites.PLAYER = ' + rows(ART.player),
  'Sprites.POTION = ' + rows(ART.potion),
  '',
  '-- Each enemy: two idle frames and an attack pose, facing right.',
  'Sprites.ENEMIES = {',
  ...Object.entries(ENEMY_ART).map(
    ([k, a]) => `\t${k} = {\n\t\tidle = { ${rows(a.idle[0])}, ${rows(a.idle[1])} },\n\t\tattack = ${rows(a.attack)},\n\t},`,
  ),
  '}',
  '',
  'return Sprites',
  '',
];
writeFileSync(fileURLToPath(new URL('../src/shared/Sprites.luau', import.meta.url)), out.join('\n'));
console.log('wrote roblox/src/shared/Sprites.luau');
